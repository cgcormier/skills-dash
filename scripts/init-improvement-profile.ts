import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { resolveReporterProfile } from "./lifecycle-profile";

const project = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const name = process.argv[2];
if (!name || !/^[a-z0-9][a-z0-9-]{0,60}$/.test(name))
  throw new Error(
    "Usage: npm.cmd run profile:init -- <new-profile-name> (lowercase letters, digits, hyphens)",
  );
const base = path.join(project, "output", "profiles", name);
await fs.mkdir(path.dirname(base), { recursive: true });
// Never turn an existing directory into a fixture or overwrite a previous run.
await fs.mkdir(base);
await fs.writeFile(
  path.join(base, "skills-dash-test-profile.json"),
  JSON.stringify({ version: 1 }, null, 2),
  { flag: "wx" },
);
const pilots = [
  {
    folder: "improvement-pilot-slugs",
    description: "Convert title lines into lowercase URL slugs.",
    task: {
      kind: "slug-lines",
      lowercase: false,
      trim: true,
      replaceSpaces: true,
      removePunctuation: true,
      omitEmpty: true,
    },
    expectation:
      "Return lowercase slugs, trim lines, replace whitespace with a hyphen, remove punctuation, and omit empty lines.",
  },
  {
    folder: "improvement-pilot-tags",
    description: "Normalize, deduplicate, and sort a list of tags.",
    task: {
      kind: "normalized-tags",
      trim: true,
      lowercase: true,
      unique: false,
      sort: true,
    },
    expectation:
      "Return unique lowercase tags in ascending order, trimming surrounding whitespace.",
  },
  {
    folder: "improvement-pilot-priorities",
    description: "Sort unique priority labels in ascending order.",
    task: {
      kind: "priority-list",
      trim: true,
      omitEmpty: true,
      unique: true,
      sort: "descending",
    },
    expectation:
      "Return unique priority labels in ascending lexicographic order, trimming lines and omitting empty lines.",
  },
];
for (const pilot of pilots) {
  const folder = path.join(base, ".agents", "skills", pilot.folder);
  await fs.mkdir(folder, { recursive: true });
  const content = `---\nname: ${pilot.folder}\ndescription: ${pilot.description}\n---\n# Disposable improvement pilot\n\n${pilot.expectation}\n\nApply the declarative task below exactly. Report any conflict between its result and the requested result as factual friction. Do not edit this file during a task.\n\n\`\`\`skill-task\n${JSON.stringify(pilot.task, null, 2)}\n\`\`\`\n`;
  await fs.writeFile(path.join(folder, "SKILL.md"), content, { flag: "wx" });
}
for (const directory of ["app-data", "webview"])
  await fs.mkdir(path.join(base, directory));
console.log(
  JSON.stringify(
    {
      profile: await resolveReporterProfile(base),
      next: "Set SKILLS_DASH_TEST_PROFILE to this profile directory, start the desktop, and enable improvement in Settings. Initial mode is Propose; the reporter refuses reports while Off.",
    },
    null,
    2,
  ),
);

async (page) => {
  const context = await page.context().browser().newContext({ viewport: { width: 1440, height: 900 } })
  const p = await context.newPage()
  const results = []
  const check = (ok, label) => { if (!ok) throw new Error(label); results.push(label) }
  const noOverflow = () => p.evaluate(() => document.documentElement.scrollWidth <= innerWidth)
  try {
    await p.goto('http://127.0.0.1:1420')
    await p.getByText('Saved locally', { exact: true }).waitFor()
    check(await p.locator('.inspector').count() === 0 && await p.locator('.masthead').count() === 0, 'Fresh start has no masthead or unsolicited preview')
    check(await p.getByRole('button', {name:'Filters',exact:true}).getAttribute('aria-expanded') === 'false', 'Secondary filters start collapsed')
    check(await p.getByLabel('Filter status', {exact:true}).isHidden(), 'Collapsed filters are absent from keyboard navigation')
    await p.screenshot({path:'output/playwright/cleanup-desktop.png'})
    await p.locator('.skill-name').first().click()
    check(await p.locator('.inspector').isVisible(), 'Selecting a skill reveals its preview')
    await p.getByRole('button', {name:'Hide preview',exact:true}).click()
    check(await p.locator('.inspector').count() === 0 && await p.evaluate(() => !new URL(location.href).searchParams.has('skill')), 'Hide preview clears selection and restores list width')
    check(await p.getByLabel('Search skills', {exact:true}).evaluate(el => el === document.activeElement), 'Hiding preview returns keyboard focus to search')
    await p.goBack()
    check(await p.locator('.inspector').isVisible(), 'History restores the selected preview')
    await p.getByRole('button', {name:'Hide preview',exact:true}).click()
    await p.getByRole('button', {name:'Filters',exact:true}).click()
    await p.getByLabel('Filter status', {exact:true}).selectOption('draft')
    await p.getByRole('button', {name:'Filters',exact:true}).click()
    check(await p.locator('tbody tr').count() === 2 && await p.getByRole('button',{name:'Clear filters',exact:true}).isVisible(), 'Collapsed active filters retain results and a visible reset')
    await p.getByRole('button',{name:'Clear filters',exact:true}).click()
    for (const [width,height] of [[375,600],[390,844],[768,600],[1280,720]]) {
      await p.setViewportSize({width,height})
      await p.evaluate(() => scrollTo(0,0))
      check(await noOverflow(), `${width}x${height} index fits without horizontal page overflow`)
      await p.getByRole('button',{name:'Filters',exact:true}).click()
      check(await noOverflow(), `${width}x${height} expanded filters fit the viewport`)
      await p.getByRole('button',{name:'Filters',exact:true}).click()
      await p.locator('.skill-name').last().focus()
      check(await p.evaluate(() => scrollY > 0 && document.querySelector('.topbar').getBoundingClientRect().top === 0), `${width}x${height} last record is reachable with a stable header`)
      const row = await p.locator('.skill-name').last().boundingBox()
      check(row.y >= 57 && row.y + row.height <= height, `${width}x${height} focused record is not covered or clipped`)
      await p.evaluate(() => scrollTo(0,0))
      await p.screenshot({path:`output/playwright/cleanup-${width}.png`})
    }
    await p.setViewportSize({width:390,height:844})
    await p.locator('.skill-name').first().click()
    check(await p.locator('.full-dossier').isVisible() && await noOverflow(), 'Narrow selection opens a full dossier that fits')
    await p.getByRole('button',{name:'Back to index',exact:true}).click()
    await p.getByRole('button',{name:'Atlas',exact:true}).click()
    const map = p.getByRole('region',{name:'Relationship map',exact:true})
    await map.focus()
    await p.keyboard.press('ArrowRight')
    await p.waitForFunction(() => document.querySelector('.atlas-scroll').scrollLeft > 0)
    check(await noOverflow(), 'Keyboard scrolls the labeled relationship map without page overflow')
    await p.getByRole('button',{name:'Index',exact:true}).click()
    await p.getByRole('button',{name:'Open navigation',exact:true}).click()
    await p.getByRole('button',{name:'Preferences',exact:true}).click()
    await p.getByLabel('Visual effects',{exact:true}).selectOption('none')
    await p.getByRole('button',{name:'Done',exact:true}).click()
    await p.emulateMedia({reducedMotion:'reduce'})
    check(await p.locator('tbody tr').count() === 12 && await noOverflow(), 'Reduced effects and motion preserve all records and fit')
    return results
  } finally { await context.close() }
}
